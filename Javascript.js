let currentLanguage = localStorage.getItem("promaxRealEstateLanguage") || "ht";

const translatePage = language => {
  const languagePack = translations[language] || translations.ht;
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = languagePack[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll(".lang-btn").forEach(button => button.classList.toggle("active", button.dataset.lang === language));
  localStorage.setItem("promaxRealEstateLanguage", language);
};

const showToast = message => {
  const toast = document.getElementById("toast");
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(showToast.timeout);
  showToast.timeout = setTimeout(() => toast.classList.remove("show"), 3000);
};

const menuToggle = document.getElementById("menuToggle");
const mainNav = document.getElementById("mainNav");
if (menuToggle && mainNav) {
  menuToggle.addEventListener("click", () => {
    const open = mainNav.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(open));
  });
  mainNav.querySelectorAll("a").forEach(link => link.addEventListener("click", () => {
    mainNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  }));
}

document.querySelectorAll(".lang-btn").forEach(button => button.addEventListener("click", () => translatePage(button.dataset.lang)));

const modal = document.getElementById("enrollModal");
const openModal = () => {
  if (!modal) return;
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  modal.querySelector("input")?.focus();
};
const closeModal = () => {
  if (!modal) return;
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
};
document.getElementById("openEnroll")?.addEventListener("click", openModal);
document.getElementById("announcementEnroll")?.addEventListener("click", openModal);
document.getElementById("closeEnroll")?.addEventListener("click", closeModal);
modal?.addEventListener("click", event => { if (event.target === modal) closeModal(); });
document.addEventListener("keydown", event => { if (event.key === "Escape") closeModal(); });

document.getElementById("enrollForm")?.addEventListener("submit", event => {
  event.preventDefault();
  const formData = Object.fromEntries(new FormData(event.currentTarget).entries());
  localStorage.setItem("promaxRealEstateStudent", JSON.stringify({ ...formData, submittedAt: new Date().toISOString() }));
  const formStatus = document.getElementById("formStatus");
  if (formStatus) formStatus.textContent = translations[currentLanguage].submitted;
  event.currentTarget.reset();
});

const progress = JSON.parse(localStorage.getItem("promaxRealEstateProgress") || "{}");
document.querySelectorAll(".course-card").forEach(card => {
  const key = card.dataset.course;
  const bar = card.querySelector(".progress-track span");
  if (progress[key] && bar) bar.style.width = "20%";
  card.querySelector(".course-start")?.addEventListener("click", () => {
    progress[key] = true;
    localStorage.setItem("promaxRealEstateProgress", JSON.stringify(progress));
    if (bar) bar.style.width = "20%";
    showToast(translations[currentLanguage].courseOpened);
  });
});

const quizButtons = document.querySelectorAll(".quiz-options button");
const quizResult = document.getElementById("quizResult");
const scoreValue = document.getElementById("scoreValue");
const scoreRing = document.querySelector(".score-ring");
quizButtons.forEach(button => button.addEventListener("click", () => {
  quizButtons.forEach(option => option.classList.remove("correct", "wrong"));
  const correct = button.dataset.answer === "correct";
  button.classList.add(correct ? "correct" : "wrong");
  if (quizResult) quizResult.textContent = translations[currentLanguage][correct ? "correct" : "incorrect"];
  if (scoreValue) scoreValue.textContent = correct ? "100" : "0";
  if (scoreRing) scoreRing.style.background = `conic-gradient(var(--orange) ${correct ? 360 : 0}deg, #251005 0deg)`;
}));

document.getElementById("certificateBtn")?.addEventListener("click", () => showToast(translations[currentLanguage].requirements));
const yearElement = document.getElementById("year");
if (yearElement) yearElement.textContent = new Date().getFullYear();

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => { if (entry.isIntersecting) entry.target.classList.add("visible"); });
}, { threshold: .12 });
document.querySelectorAll(".reveal").forEach(element => observer.observe(element));

translatePage(currentLanguage);

